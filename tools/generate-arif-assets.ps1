# Generates the embedded asset headers for the vendored arifclient ClickGUI
# (DemokratikKongoCore/ext/arifgui/arif_fonts.h + arif_iconpack.h).
#
#   PowerShell -ExecutionPolicy Bypass -File tools\generate-arif-assets.ps1
#
# The arif ClickGUI loads its fonts and PNG icon pack from resource files at
# runtime. The injected core has no resource folder on disk, so the exact same
# bytes are baked into the DLL as C arrays by this script (mirrors the existing
# ext/fonts/*.h pattern).
#
# Re-run whenever the arifclient resource/fonts or resource/icons files change.

param(
    [string]$ArifRoot = "C:\Users\user\Desktop\arifclient\native\clickgui",
    [string]$OutDir   = "$PSScriptRoot\..\DemokratikKongoCore\ext\arifgui"
)

$ErrorActionPreference = "Stop"

function Write-CByteArray {
    param(
        [System.Text.StringBuilder]$Sb,
        [string]$Name,
        [byte[]]$Data
    )
    $Sb.AppendLine("const unsigned char $Name[$($Data.Length)] = {") | Out-Null
    for ($i = 0; $i -lt $Data.Length; $i += 16) {
        $end = [Math]::Min($i + 16, $Data.Length) - 1
        $parts = for ($j = $i; $j -le $end; $j++) { "0x{0:X2}" -f $Data[$j] }
        $Sb.AppendLine("    " + ($parts -join ", ") + ",") | Out-Null
    }
    $Sb.AppendLine("};") | Out-Null
}

New-Item -ItemType Directory -Force $OutDir | Out-Null

# ---------------------------------------------------------------------------
# Fonts (Plus Jakarta Sans + Font Awesome 6 Free Solid)
# ---------------------------------------------------------------------------
$fontDir = Join-Path $ArifRoot "resource\fonts"
$fonts = @(
    @{ File = "PlusJakartaSans-Regular.ttf";  Symbol = "arif_font_pjs_regular" },
    @{ File = "PlusJakartaSans-SemiBold.ttf"; Symbol = "arif_font_pjs_semibold" },
    @{ File = "PlusJakartaSans-Bold.ttf";     Symbol = "arif_font_pjs_bold" },
    @{ File = "JetBrainsMono-Regular.ttf";    Symbol = "arif_font_jbmono" },
    @{ File = "fa-solid-900.ttf";             Symbol = "arif_fa_solid_900" }
)

$sb = [System.Text.StringBuilder]::new()
$sb.AppendLine("#pragma once") | Out-Null
$sb.AppendLine("// AUTO-GENERATED by tools/generate-arif-assets.ps1 - do not edit by hand.") | Out-Null
$sb.AppendLine("// Plus Jakarta Sans (SIL OFL 1.1) + Font Awesome 6 Free Solid (CC BY 4.0),") | Out-Null
$sb.AppendLine("// taken verbatim from arifclient/native/clickgui/resource/fonts.") | Out-Null

foreach ($font in $fonts) {
    $path = Join-Path $fontDir $font.File
    if (-not (Test-Path $path)) { throw "missing font: $path" }
    $bytes = [System.IO.File]::ReadAllBytes($path)
    Write-Host ("font {0,-32} {1,8} bytes -> {2}" -f $font.File, $bytes.Length, $font.Symbol)
    $sb.AppendLine("") | Out-Null
    Write-CByteArray -Sb $sb -Name $font.Symbol -Data $bytes
}

$fontHeader = Join-Path $OutDir "arif_fonts.h"
[System.IO.File]::WriteAllText($fontHeader, $sb.ToString())
Write-Host "wrote $fontHeader"

# ---------------------------------------------------------------------------
# PNG icon pack (resource/icons/icon_<name>.png -> blob table)
# ---------------------------------------------------------------------------
$iconDir = Join-Path $ArifRoot "resource\icons"
$pngs = Get-ChildItem $iconDir -Filter "icon_*.png" -File | Sort-Object Name
if ($pngs.Count -eq 0) { throw "no icons found in $iconDir" }

$sb = [System.Text.StringBuilder]::new()
$sb.AppendLine("#pragma once") | Out-Null
$sb.AppendLine("// AUTO-GENERATED by tools/generate-arif-assets.ps1 - do not edit by hand.") | Out-Null
$sb.AppendLine("// feather raster icon pack (white glyph, transparent background) from") | Out-Null
$sb.AppendLine("// arifclient/native/clickgui/resource/icons. Decoded with WIC at startup.") | Out-Null
$sb.AppendLine("") | Out-Null
$sb.AppendLine("struct ArifIconBlob {") | Out-Null
$sb.AppendLine("    const char* name;") | Out-Null
$sb.AppendLine("    const unsigned char* bytes;") | Out-Null
$sb.AppendLine("    unsigned int size;") | Out-Null
$sb.AppendLine("};") | Out-Null

$entries = @()
foreach ($png in $pngs) {
    $key = $png.BaseName.Substring(5)   # strip "icon_"
    $symbol = "arif_icon_" + ($key -replace '[^A-Za-z0-9_]', '_')
    $bytes = [System.IO.File]::ReadAllBytes($png.FullName)
    Write-Host ("icon {0,-24} {1,7} bytes -> {2}" -f $png.Name, $bytes.Length, $symbol)
    $sb.AppendLine("") | Out-Null
    Write-CByteArray -Sb $sb -Name $symbol -Data $bytes
    $entries += "    { ""$key"", $symbol, (unsigned int)sizeof($symbol) },"
}

$sb.AppendLine("") | Out-Null
$sb.AppendLine("inline const ArifIconBlob arif_icon_blobs[] = {") | Out-Null
foreach ($line in $entries) { $sb.AppendLine($line) | Out-Null }
$sb.AppendLine("};") | Out-Null
$sb.AppendLine("inline const unsigned int arif_icon_blob_count = sizeof(arif_icon_blobs) / sizeof(arif_icon_blobs[0]);") | Out-Null

$iconHeader = Join-Path $OutDir "arif_iconpack.h"
[System.IO.File]::WriteAllText($iconHeader, $sb.ToString())
Write-Host "wrote $iconHeader"
