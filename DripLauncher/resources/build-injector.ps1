# RuntimeHostInjector - embed script.
#
# Takes the built RuntimeHostInjector.dll (see RuntimeHostInjector.vcxproj)
# and emits it as a base64 header (src/launcher/injectorDllData.h) that the
# launcher embeds and extracts at inject time.
#
# Order of operations after editing src/agent/injectAgent.cpp:
#   .\build.ps1                                # builds exe + injector dll
#   powershell -File DripLauncher\resources\build-injector.ps1
#   .\build.ps1                                # launcher picks up the header

$ErrorActionPreference = "Stop"

$Root = Split-Path -Parent $PSScriptRoot   # DripLauncher/
$Dll = Join-Path $Root "build\RuntimeHostInjector.dll"
$OutHeader = Join-Path $Root "src\launcher\injectorDllData.h"

if (-not (Test-Path $Dll)) {
    Write-Error "RuntimeHostInjector.dll not found at $Dll - run build.ps1 first."
}

$bytes = [System.IO.File]::ReadAllBytes($Dll)
$base64 = [System.Convert]::ToBase64String($bytes)

# Fixed-size chunking: 80 columns keeps the header readable and is
# compilable as adjacent C string literals.
$sb = [System.Text.StringBuilder]::new()
for ($i = 0; $i -lt $base64.Length; $i += 80) {
    $len = [Math]::Min(80, $base64.Length - $i)
    [void]$sb.AppendLine('    "' + $base64.Substring($i, $len) + '"')
}

$header = @"
#pragma once

// Generated by resources/build-injector.ps1 -- do not edit by hand.
//
// RuntimeHostInjector.dll, base64-encoded. The launcher extracts it into its
// temp cache and runs it inside a java.exe host
// (java -agentpath:<dll>=pid=<pid>;dll=<payload> -version), so the remote
// load is performed by the JDK's own tool process rather than the launcher.
// Source: src/agent/injectAgent.cpp.
//
// The base64 blob is $($base64.Length) characters.

namespace dk::injectordll {

inline const char* kInjectorDllBase64() {
    return
$($sb.ToString().TrimEnd())
    ;
}

} // namespace dk::injectordll
"@

$header = $header -replace "`r`n", "`n"
[System.IO.File]::WriteAllText($OutHeader, $header, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "Injector DLL: $Dll ($($bytes.Length) bytes)"
Write-Host "Wrote: $OutHeader"
