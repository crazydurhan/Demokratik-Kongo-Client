# RuntimeHost loader mod (Forge 1.8.9) - build script.
#
# Compiles resources/mod/RuntimeHostMod.java against a Forge 1.8.9 universal
# JAR (compile-time only; the game provides the real classes), packages the
# class plus mcmod.info into a JAR and emits it as a base64 header into
# src/launcher/modJarData.h.
#
# Run manually after editing RuntimeHostMod.java:
#   powershell -ExecutionPolicy Bypass -File resources\build-mod.ps1
#
# Requires a JDK (javac + jar) on PATH or found via JAVA_HOME.
param(
    [string]$JdkHome = $null,
    [string]$ForgeJar = $null
)

$ErrorActionPreference = "Stop"

$Root = Split-Path -Parent $PSScriptRoot   # DripLauncher/
$Java = Join-Path $Root "resources\mod\RuntimeHostMod.java"
$Mcmod = Join-Path $Root "resources\mod\mcmod.info"
$StateDir = Join-Path $Root "resources\generated\mod"
$OutHeader = Join-Path $Root "src\launcher\modJarData.h"

function Resolve-Jdk {
    param([string]$Hint)

    $candidates = @()
    if ($Hint) { $candidates += (Join-Path $Hint "bin\javac.exe") }
    if ($env:JAVA_HOME) { $candidates += (Join-Path $env:JAVA_HOME "bin\javac.exe") }

    $javac = Get-Command javac.exe -ErrorAction SilentlyContinue
    if ($javac) { $candidates += $javac.Path }

    foreach ($c in $candidates) {
        if ($c -and (Test-Path $c)) { return $c }
    }
    return $null
}

$javac = Resolve-Jdk -Hint $JdkHome
if (-not $javac) {
    Write-Error "javac.exe not found. Install a JDK or set JAVA_HOME / pass -JdkHome."
}

$jarTool = Join-Path (Split-Path -Parent $javac) "jar.exe"
if (-not (Test-Path $jarTool)) {
    Write-Error "jar.exe not found next to javac.exe: $jarTool"
}

if (-not $ForgeJar) {
    $ForgeJar = Join-Path $env:TEMP "opencode\forge\forge-universal.jar"
}
if (-not (Test-Path $ForgeJar)) {
    $url = "https://maven.minecraftforge.net/net/minecraftforge/forge/1.8.9-11.15.1.2318-1.8.9/forge-1.8.9-11.15.1.2318-1.8.9-universal.jar"
    Write-Host "Downloading Forge universal JAR (compile-time only): $url"
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $ForgeJar) | Out-Null
    Invoke-WebRequest -Uri $url -OutFile $ForgeJar
}

if (Test-Path $StateDir) { Remove-Item -Recurse -Force $StateDir }
New-Item -ItemType Directory -Force -Path $StateDir | Out-Null

$classes = Join-Path $StateDir "classes"
New-Item -ItemType Directory -Force -Path $classes | Out-Null

Write-Host "Compiling loader mod (javac: $javac)"
# -source/-target instead of --release keeps the bytecode at Java 8 level
# without requiring the (absent) 1.8.9 Forge target symbols.
& $javac -source 8 -target 8 -nowarn -cp $ForgeJar -d $classes $Java
if ($LASTEXITCODE -ne 0) { Write-Error "javac failed with exit code $LASTEXITCODE" }

Copy-Item $Mcmod (Join-Path $classes "mcmod.info") -Force

$jarPath = Join-Path $StateDir "runtimehost-mod.jar"
& $jarTool --create --file $jarPath -C $classes .
if ($LASTEXITCODE -ne 0) { Write-Error "jar failed with exit code $LASTEXITCODE" }

$bytes = [System.IO.File]::ReadAllBytes($jarPath)
$base64 = [System.Convert]::ToBase64String($bytes)

# Fixed-size chunking: 80 columns keeps the header readable and is
# compilable as adjacent C string literals.
$sb = [System.Text.StringBuilder]::new()
for ($i = 0; $i -lt $base64.Length; $i += 80) {
    $len = [Math]::Min(80, $base64.Length - $i)
    [void]$sb.AppendLine('    "' + $base64.Substring($i, $len) + '"')
}

$version = (& $javac -version 2>&1) -join " "

$header = @"
#pragma once

// Generated by resources/build-mod.ps1 -- do not edit by hand.
//
// The Forge 1.8.9 loader mod, base64-encoded. The launcher writes it into
// the Lunar Client mods folder; the game loads it and the mod System.load()s
// the core DLL named by %APPDATA%\RuntimeHost\load\current.txt.
// Source: resources/mod/RuntimeHostMod.java (compiler: $version).
//
// The trailing base64 length is ${($base64.Length)} characters.

namespace dk::modjar {

inline const char* kModJarBase64() {
    return
$($sb.ToString().TrimEnd())
    ;
}

} // namespace dk::modjar
"@

# Write as UTF-8 without BOM (MSVC cares) with normalized newlines.
$header = $header -replace "`r`n", "`n"
[System.IO.File]::WriteAllText($OutHeader, $header, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "Loader mod JAR: $jarPath ($($bytes.Length) bytes)"
Write-Host "Wrote: $OutHeader"
