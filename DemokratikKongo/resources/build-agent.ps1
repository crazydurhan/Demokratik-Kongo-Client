# RuntimeHost — agent JAR builder.
#
# Compiles resources/RuntimeHostAgent.java (target: Java 8 bytecode so the
# class runs on every JDK the target game might use) and emits the JAR as a
# base64 string into src/launcher/agentJarData.h.
#
# Run manually after editing RuntimeHostAgent.java:
#   powershell -ExecutionPolicy Bypass -File resources\build-agent.ps1
#
# Requires a JDK (javac + jar) on PATH or found via JAVA_HOME.
param(
    [string]$JdkHome = $null
)

$ErrorActionPreference = "Stop"

$Root = Split-Path -Parent $PSScriptRoot   # DemokratikKongo/
$Java = Join-Path $Root "resources\RuntimeHostAgent.java"
$StateDir = Join-Path $Root "resources\generated"
$OutHeader = Join-Path $Root "src\launcher\agentJarData.h"

function Resolve-Jdk {
    param([string]$Hint)

    $candidates = @()
    if ($Hint) { $candidates += (Join-Path $Hint "bin\javac.exe") }
    if ($env:JAVA_HOME) { $candidates += (Join-Path $env:JAVA_HOME "bin\javac.exe") }

    $javac = Get-Command javac.exe -ErrorAction SilentlyContinue
    if ($javac) { $candidates += $javac.Path }

    foreach ($c in $candidates) {
        if ($c -and (Test-Path $c)) { return $c }
    }
    return $null
}

$javac = Resolve-Jdk -Hint $JdkHome
if (-not $javac) {
    Write-Error "javac.exe not found. Install a JDK or set JAVA_HOME / pass -JdkHome."
}

$jarTool = Join-Path (Split-Path -Parent $javac) "jar.exe"
if (-not (Test-Path $jarTool)) {
    Write-Error "jar.exe not found next to javac.exe: $jarTool"
}

if (Test-Path $StateDir) { Remove-Item -Recurse -Force $StateDir }
New-Item -ItemType Directory -Force -Path $StateDir | Out-Null

$classes = Join-Path $StateDir "classes"
New-Item -ItemType Directory -Force -Path $classes | Out-Null

Write-Host "Compiling agent (javac: $javac)"
# -source/-target instead of --release: com.sun.tools.attach is not in the
# --release 8 ct.sym set, so --release fails. -source 8 produces bytecode
# that runs on JDK 8 through current.
& $javac -source 8 -target 8 -nowarn -d $classes $Java
if ($LASTEXITCODE -ne 0) { Write-Error "javac failed with exit code $LASTEXITCODE" }

# Manifest: Agent-Class is required for dynamic attach; Main-Class lets the
# same JAR run standalone as a helper (java -jar agent.jar <pid> <dllPath>).
# Can-Retransform-Classes is required by JDK 9+ to accept the dual-argument
# agentmain overload.
$manifest = "Manifest-Version: 1.0`r`nMain-Class: RuntimeHostAgent`r`nAgent-Class: RuntimeHostAgent`r`nCan-Retransform-Classes: true`r`n"
$manifestPath = Join-Path $StateDir "manifest.txt"
[System.IO.File]::WriteAllText($manifestPath, $manifest, [System.Text.Encoding]::ASCII)

$jarPath = Join-Path $StateDir "RuntimeHostAgent.jar"
& $jarTool --create --file $jarPath --manifest $manifestPath -C $classes .
if ($LASTEXITCODE -ne 0) { Write-Error "jar failed with exit code $LASTEXITCODE" }

$bytes = [System.IO.File]::ReadAllBytes($jarPath)
$base64 = [System.Convert]::ToBase64String($bytes)

# Fixed-size chunking: 80 columns keeps the header readable and is
# compilable as adjacent C string literals.
$sb = [System.Text.StringBuilder]::new()
for ($i = 0; $i -lt $base64.Length; $i += 80) {
    $len = [Math]::Min(80, $base64.Length - $i)
    [void]$sb.AppendLine('    "' + $base64.Substring($i, $len) + '"')
}

$version = (& $javac -version 2>&1) -join " "

$header = @"
#pragma once

// Generated by resources/build-agent.ps1 — do not edit by hand.
//
// RuntimeHostAgent.jar, base64-encoded. The launcher writes it next to the
// extracted core DLL and passes it to the target JVM via its attach API.
// Source: resources/RuntimeHostAgent.java (compiler: $version).
//
// The trailing base64 length is ${($base64.Length)} characters.

namespace dk::agentjar {

inline const char* kAgentJarBase64() {
    return
$($sb.ToString().TrimEnd())
    ;
}

} // namespace dk::agentjar
"@

# PowerShell here-strings expand $() but we want the arrays as literals; do a
# final normalization of newlines and write as UTF-8 without BOM (MSVC cares).
$header = $header -replace "`r`n", "`n"
[System.IO.File]::WriteAllText($OutHeader, $header, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "Agent JAR: $jarPath ($($bytes.Length) bytes)"
Write-Host "Wrote: $OutHeader"
